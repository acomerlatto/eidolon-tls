#!/usr/bin/env bash
# Regenerates the internal copy of the x/net HTTP/2 engine from the net fork.
#
# Only the legacy engine is copied: the files that `go list -tags http2legacy`
# selects with the project's Go version. The Go 1.27 wrappers and the variants
# for older Go versions are left out because they declare the same symbols.
#
# Usage: scripts/sync-xnet.sh [path-to-net-fork]   (default: ../net)
#
# Local deviations live in scripts/xnet-patches/*.patch and are applied in
# lexical order after the copy, so a re-sync never drops them silently.
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
src=$(cd "${1:-$root/../net}" && pwd)
mod=github.com/acomerlatto/eidolon-tls

# source package -> destination directory (relative to the repo root)
pkgs=(
	"http2:internal/http2"
	"http2/hpack:internal/http2/hpack"
	"internal/httpcommon:internal/httpcommon"
	"internal/httpsfv:internal/httpsfv"
	"internal/gate:internal/gate"         # tests only
	"internal/testcert:internal/testcert" # tests only
)

want_go=$(awk '$1 == "go" { print "go" $2; exit }' "$root/go.mod")
have_go=$(go env GOVERSION)
if [[ ${have_go%.*} != "${want_go%.*}" ]]; then
	echo "sync-xnet: file selection depends on the Go version: go.mod wants $want_go, toolchain is $have_go" >&2
	exit 1
fi

if [[ -n $(git -C "$src" status --porcelain) ]]; then
	echo "sync-xnet: $src has uncommitted changes" >&2
	exit 1
fi
commit=$(git -C "$src" rev-parse HEAD)
commit_date=$(git -C "$src" log -1 --format=%cs)

list() { # list <pkg> <template>
	(cd "$src" && go list -tags http2legacy -f "$2" "./$1")
}

included=()
excluded=()
for entry in "${pkgs[@]}"; do
	pkg=${entry%%:*}
	dst=$root/${entry#*:}
	mkdir -p "$dst"
	find "$dst" -maxdepth 1 -type f \( -name '*.go' -o -name LICENSE \) -delete

	files=$(list "$pkg" '{{join .GoFiles " "}} {{join .TestGoFiles " "}} {{join .XTestGoFiles " "}}')
	for f in $files; do
		cp "$src/$pkg/$f" "$dst/$f"
		included+=("$pkg/$f")
	done
	for f in $(list "$pkg" '{{join .IgnoredGoFiles " "}}'); do
		excluded+=("$pkg/$f")
	done
	cp "$src/LICENSE" "$dst/LICENSE"
done

gofiles=()
for entry in "${pkgs[@]}"; do
	gofiles+=("$root/${entry#*:}"/*.go)
done

# Build constraints were resolved by the selection above.
sed -i '/^\/\/go:build /d' "${gofiles[@]}"
# Import paths: longest prefix first.
sed -i -E \
	-e "s#\"golang.org/x/net/http2/hpack\"#\"$mod/internal/http2/hpack\"#" \
	-e "s#\"golang.org/x/net/http2\"#\"$mod/internal/http2\"#" \
	-e "s#\"golang.org/x/net/internal/(httpcommon|httpsfv|gate|testcert)\"#\"$mod/internal/\\1\"#" \
	-e 's#^(package [a-z0-9_]+) // import ".*"$#\1#' \
	"${gofiles[@]}"

if grep -rn --include='*.go' -E '"golang.org/x/net/(http2|internal/)' "${gofiles[@]}"; then
	echo "sync-xnet: unrewritten x/net import left" >&2
	exit 1
fi

# Format before patching: the rewritten imports move, and patches are made
# against the formatted files kept in the repository.
gofmt -w "${gofiles[@]}"

shopt -s nullglob
patches=("$root"/scripts/xnet-patches/*.patch)
for p in "${patches[@]}"; do
	git -C "$root" apply --verbose "$p"
done

gofmt -w "${gofiles[@]}"

{
	echo "# Upstream of the internal HTTP/2 engine"
	echo
	echo "Generated by \`scripts/sync-xnet.sh\`. Do not edit by hand: change the script or add a patch."
	echo
	echo "- Source: \`golang.org/x/net\` via the fork \`$(git -C "$src" remote get-url origin 2>/dev/null || echo "$src")\`"
	echo "- Commit: \`$commit\` ($commit_date)"
	echo "- Toolchain used for file selection: \`$have_go\`, tags \`http2legacy\`"
	echo "- License: BSD-3-Clause, copied as \`LICENSE\` into each package directory"
	echo
	echo "Packages (\`internal/gate\` and \`internal/testcert\` are used only by tests):"
	echo
	for entry in "${pkgs[@]}"; do
		echo "- \`${entry%%:*}\` → \`${entry#*:}\`"
	done
	echo
	echo "## Local patches"
	echo
	if ((${#patches[@]} == 0)); then
		echo "None."
	else
		for p in "${patches[@]}"; do
			echo "- \`scripts/xnet-patches/$(basename "$p")\`"
		done
	fi
	echo
	echo "## Excluded files"
	echo
	echo "Not selected by the build constraints: the Go 1.27 wrappers (\`*_wrap*.go\`), the variants for older Go versions and generators."
	echo
	for f in "${excluded[@]}"; do echo "- \`$f\`"; done
	echo
	echo "## Included files"
	echo
	for f in "${included[@]}"; do echo "- \`$f\`"; done
} >"$root/internal/http2/UPSTREAM.md"

echo "sync-xnet: copied ${#included[@]} files from $commit"
